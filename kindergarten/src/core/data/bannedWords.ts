/**
 * واژگان ممنوع — پیوست ب سند.
 *
 * «هرگز در متن تولیدشده توسط سامانه درباره کودک به کار نرود، و در متن
 * آزاد مربی هشدار بدهد.»
 *
 * دو رفتار متفاوت و عمدی: در تولید خودکار ممنوع است، در متن مربی فقط
 * هشدار. مربی جلویش گرفته نمی‌شود چون ممکن است دلیلی داشته باشد که
 * سامانه نمی‌داند؛ ولی باید ببیند دارد برچسب می‌زند.
 *
 * بند ۱۰.۱: «زبان مربی با طراحی فرم کنترل می‌شود.» این هشدار بخشی از
 * همان کنترل است.
 */
export const BANNED_WORDS = [
  'باهوش',
  'تنبل',
  'پرخاشگر',
  'خجالتی',
  'بیش‌فعال',
  'کم‌توجه',
  'عقب',
  'ضعیف',
  'مشکل‌دار',
  'نرمال',
  'غیرطبیعی',
  'طبیعی',
  'استعداد',
  'ضریب هوشی',
  'اختلال',
  'تشخیص',
] as const

/** نیم‌فاصله و فاصله معمولی یکی شمرده می‌شوند، وگرنه «بیش‌فعال» رد می‌شود. */
function normalise(text: string): string {
  return text.replace(/‌/g, ' ').replace(/\s+/g, ' ')
}

/** واژگان ممنوعی که در متن مربی آمده‌اند. خالی یعنی پاک است. */
export function findBannedWords(text: string): string[] {
  const haystack = normalise(text)
  return BANNED_WORDS.filter((word) => haystack.includes(normalise(word)))
}
