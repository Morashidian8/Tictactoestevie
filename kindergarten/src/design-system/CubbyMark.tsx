import styles from './CubbyMark.module.css'

/**
 * نماد کمد کودک — همان استیکری که در مهد واقعی روی جالباسی هر کودک است.
 *
 * چرا مجاز است و خط قرمز بخش ۱۰ را نمی‌شکند: این تیپ شخصیتی و استعداد
 * و امتیاز نیست. یک شناساگر است، مثل شماره کمد — و کودک سه‌ساله‌ای که
 * هنوز نامش را نمی‌خواند، خودش را از همین پیدا می‌کند.
 *
 * از شناسه کودک ساخته می‌شود، دقیقاً مثل چهره جایگزین عکس در
 * AvatarFace: پایدار است، پس امیرِ امروز و امیرِ فردا یک نماد دارند،
 * و داده تازه‌ای هم نمی‌خواهد.
 *
 * نمادها عمداً بی‌طرف‌اند: حیوان، گیاه، شکل. هیچ‌کدام درباره کودک چیزی
 * نمی‌گویند.
 */
const MARKS = ['🦕', '🌸', '⭐', '🦋', '🐢', '🍀', '🚀', '🐬', '🌙', '🦉', '🌻', '🐞']

/** هش پایدار و کوچک از شناسه. همان روشی که AvatarFace به کار می‌برد. */
function pick(seed: string): string {
  let hash = 0
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 31 + seed.charCodeAt(i)) % 100000
  }
  return MARKS[hash % MARKS.length] ?? MARKS[0]!
}

export function CubbyMark({ seed }: { seed: string }) {
  // aria-hidden: نماد معنای داده‌ای ندارد و صفحه‌خوان نباید بخواندش.
  return (
    <span className={styles.mark} aria-hidden>
      {pick(seed)}
    </span>
  )
}
