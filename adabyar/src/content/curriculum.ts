export const CURRICULUM: Record<number, LessonMeta[]> = {
  7: G7, 8: G8, 9: G9, 10: G10, 11: G11, 12: G12,
}

export const ALL_META: LessonMeta[] = Object.values(CURRICULUM).flat()

export function gradeInfo(g: number): GradeInfo {
  return GRADES.find((x) => x.id === g) ?? GRADES[0]
}

/** فصل‌های یک پایه به‌ترتیب ظاهرشدن در کتاب */
export function unitsOf(grade: number): string[] {
  const seen: string[] = []
  for (const l of CURRICULUM[grade] ?? []) if (!seen.includes(l.unit)) seen.push(l.unit)
  return seen
}
